// Refreshes the demo board's copy of the wire schema from a running party
// server (`make run`, then `make demo-schema`). The demo serves it at
// /api/v1/schema so MfClient decodes exactly as it does against the board.
//
//   node tools/demo-schema.mjs [http://127.0.0.1:8090]
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const base = (process.argv[2] ?? process.env.PARTY ?? 'http://127.0.0.1:8090').replace(/\/$/, '');
const out = fileURLToPath(new URL('../ui/projects/party-demo/src/schema.ts', import.meta.url));

const response = await fetch(`${base}/api/v1/schema`);
if (!response.ok) {
  console.error(`${base}/api/v1/schema answered ${response.status}; is the server running (make run)?`);
  process.exit(1);
}
const doc = await response.json();
const names = doc.messages.map((m) => m.name);
writeFileSync(
  out,
  [
    '// Generated by tools/demo-schema.mjs from a running party server; do not edit.',
    `// ${names.length} messages.`,
    `export const SCHEMA: { messages: { name: string; fields: unknown[] }[] } = ${JSON.stringify(doc)};`,
    '',
  ].join('\n'),
);
console.log(`wrote ${out} (${names.length} messages)`);
